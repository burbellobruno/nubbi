const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const source = fs.readFileSync(path.join(__dirname, "../public/app.js"), "utf8");
const configs = {};
const ctx = { cfg: id => configs[id] ||= {}, EMO: { feliz: "", triste: "", neutral: "" } };
vm.createContext(ctx);
vm.runInContext(source.slice(source.indexOf("function relationshipCfg("), source.indexOf("function sys(")), ctx);
assert.equal(ctx.relationshipCfg("a").relation.trust, 50);
ctx.captureExplicitMemory("a", "Recuerda que mi gato se llama Sol");
ctx.captureExplicitMemory("a", "Recuerda que mi gato se llama Sol");
assert.equal(configs.a.autoMem.length, 1);
ctx.captureExplicitMemory("a", "Esto no es un recuerdo explícito");
assert.equal(configs.a.autoMem.length, 1);
ctx.evolveRelationship("a", "Gracias", "feliz");
assert.equal(configs.a.relation.trust, 52);
assert.equal(configs.a.relation.affinity, 51);
ctx.evolveRelationship("a", undefined, "triste");
assert.equal(configs.a.relation.trust, 52);
ctx.evolveRelationship("a", "no te quiero", "neutral");
assert.equal(configs.a.relation.affinity, 51);
ctx.evolveRelationship("a", "no, gracias", "neutral");
assert.equal(configs.a.relation.trust, 52);
configs.a.relation.auto = false;
ctx.evolveRelationship("a", "te odio", "triste");
assert.equal(configs.a.relation.trust, 52);
configs.a.relation.auto = true;
configs.a.relation.trust = 100;
ctx.evolveRelationship("a", "gracias", "feliz");
assert.equal(configs.a.relation.trust, 100);
configs.b = JSON.parse(JSON.stringify(configs.a));
ctx.evolveRelationship("b", "te odio", "triste");
assert.equal(configs.a.relation.trust, 100);
assert.equal(configs.b.relation.trust, 98);
assert.ok(source.includes("turn(null,t)"));
assert.ok(source.includes("async function turn(extra,relationshipMessage)"));
console.log("V5: memoria, deduplicación, límites, negaciones, evolución desactivada y aislamiento de ramas: OK");
